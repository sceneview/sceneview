// ─── Legal disclaimer ─────────────────────────────────────────────────────────

const DISCLAIMER =
  "\n\n---\n*Generated by rerun-3d-mcp. Review before production use. Rerun is a trademark of Rerun AB — this MCP is not affiliated. See [LICENSE](https://github.com/sceneview/sceneview/blob/main/mcp/packages/rerun/LICENSE).*";

function withDisclaimer<T extends { type: string; text: string }>(content: T[]): T[] {
  if (content.length === 0) return content;
  const last = content[content.length - 1]!;
  return [
    ...content.slice(0, -1),
    { ...last, text: last.text + DISCLAIMER },
  ];
}

// ─── Types ────────────────────────────────────────────────────────────────────

export interface ToolTextContent {
  type: "text";
  text: string;
}

export interface ToolResult {
  content: ToolTextContent[];
  structuredContent?: Record<string, unknown>;
  isError?: boolean;
}

export interface ToolAnnotations {
  readOnlyHint: boolean;
  openWorldHint: boolean;
  destructiveHint: boolean;
  title?: string;
}

export interface ToolDefinition {
  name: string;
  description: string;
  inputSchema: {
    type: "object";
    properties?: Record<string, unknown>;
    required?: string[];
    additionalProperties?: boolean;
  };
  outputSchema?: { type: "object"; properties?: Record<string, unknown>; required?: string[]; additionalProperties?: boolean };
  /**
   * MCP behaviour hints — see mcp/src/tools/types.ts for the full rationale.
   * Optional in the type to keep migrations easy; runtime contract test in
   * mcp-gateway/test/registry.test.ts asserts every tool defines them.
   */
  annotations?: ToolAnnotations;
}

export interface DispatchContext {
  userId?: string;
  apiKeyId?: string;
  tier?: "free" | "pro" | "team";
  extras?: Record<string, unknown>;
}

