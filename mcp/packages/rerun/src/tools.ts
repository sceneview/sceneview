/**
 * Dispatch a tool call by name. Pure business logic: no auth, no rate
 * limiting, no billing. Those concerns live in the caller (stdio server or
 * gateway).
 */
export async function dispatchTool(
  toolName: string,
  rawArgs: Record<string, unknown> | undefined,
  _ctx: DispatchContext = {},
): Promise<ToolResult> {
  switch (toolName) {
    // ── setup_rerun_project ───────────────────────────────────────────────
    case "setup_rerun_project": {
      const args = rawArgs ?? {};
      const platform = args.platform as SetupPlatform;
      if (!platform || !SETUP_PLATFORMS.includes(platform)) {
        return {
          content: [
            {
              type: "text",
              text: `Invalid platform "${platform}". Valid: ${SETUP_PLATFORMS.join(", ")}`,
            },
          ],
          isError: true,
        };
      }

      const result = generateSetupProject({
        platform,
        targetDir: args.targetDir as string | undefined,
        includeSidecar: args.includeSidecar as boolean | undefined,
      });

      const body: string[] = [
        `## Rerun setup — ${platform}`,
        ``,
        `### Files`,
        ``,
      ];
      for (const f of result.files) {
        body.push(`**\`${f.path}\`**`);
        body.push("```" + f.language);
        body.push(f.contents.trimEnd());
        body.push("```");
        body.push("");
      }
      body.push(`### Instructions`, ``);
      for (const step of result.instructions) {
        body.push(`- ${step}`);
      }

      return {
        content: withDisclaimer([{ type: "text", text: body.join("\n") }]),
        structuredContent: { ...result },
      };
    }

    // ── generate_ar_logger ────────────────────────────────────────────────
    case "generate_ar_logger": {
      const args = rawArgs ?? {};
      const language = args.language as LoggerLanguage;
      const dataTypes = args.dataTypes as LoggerDataType[] | undefined;

      if (!language || !LOGGER_LANGUAGES.includes(language)) {
        return {
          content: [
            {
              type: "text",
              text: `Invalid language "${language}". Valid: ${LOGGER_LANGUAGES.join(", ")}`,
            },
          ],
          isError: true,
        };
      }
      if (!dataTypes || !Array.isArray(dataTypes) || dataTypes.length === 0) {
        return {
          content: [
            {
              type: "text",
              text: `At least one dataType is required. Valid: ${LOGGER_DATA_TYPES.join(", ")}`,
            },
          ],
          isError: true,
        };
      }

      let code: string;
      try {
        code = generateArLogger({
          language,
          dataTypes,
          rateHz: args.rateHz as number | undefined,
          host: args.host as string | undefined,
          port: args.port as number | undefined,
        });
      } catch (err) {
        return {
          content: [
            {
              type: "text",
              text: `Error: ${(err as Error).message}`,
            },
          ],
          isError: true,
        };
      }

      const langLabel = language === "kotlin" ? "Kotlin (Jetpack Compose)" : "Swift (SwiftUI)";
      const fence = language === "kotlin" ? "kotlin" : "swift";

      return {
        content: withDisclaimer([
          {
            type: "text",
            text: [
              `## AR logger — ${langLabel}`,
              ``,
              `**Data types:** ${dataTypes.join(", ")}`,
              ``,
              `**${langLabel}:**`,
              "```" + fence,
              code,
              "```",
            ].join("\n"),
          },
        ]),
      };
    }

    // ── generate_python_sidecar ───────────────────────────────────────────
    case "generate_python_sidecar": {
      const args = rawArgs ?? {};
      let code: string;
      try {
        code = generatePythonSidecar({
          port: args.port as number | undefined,
          recordingName: args.recordingName as string | undefined,
          spawnViewer: args.spawnViewer as boolean | undefined,
        });
      } catch (err) {
        return {
          content: [
            {
              type: "text",
              text: `Error: ${(err as Error).message}`,
            },
          ],
          isError: true,
        };
      }

      return {
        content: withDisclaimer([
          {
            type: "text",
            text: [
              `## Python sidecar — rerun-bridge.py`,
              ``,
              `Run with: \`pip install rerun-sdk numpy && python rerun-bridge.py\``,
              ``,
              "```python",
              code,
              "```",
            ].join("\n"),
          },
        ]),
      };
    }

    // ── embed_web_viewer ──────────────────────────────────────────────────
    case "embed_web_viewer": {
      const args = rawArgs ?? {};
      const rrdUrl = args.rrdUrl as string | undefined;
      if (!rrdUrl || typeof rrdUrl !== "string" || !rrdUrl.trim()) {
        return {
          content: [
            { type: "text", text: "rrdUrl is required." },
          ],
          isError: true,
        };
      }

      const timeRangeRaw = args.timeRange as number[] | undefined;
      const timeRange: [number, number] | undefined =
        timeRangeRaw && timeRangeRaw.length === 2
          ? [timeRangeRaw[0]!, timeRangeRaw[1]!]
          : undefined;

      let result: ReturnType<typeof generateWebViewerEmbed>;
      try {
        result = generateWebViewerEmbed({
          rrdUrl,
          containerId: args.containerId as string | undefined,
          hideWelcome: args.hideWelcome as boolean | undefined,
          viewerVersion: args.viewerVersion as string | undefined,
          timeRange,
        });
      } catch (err) {
        return {
          content: [
            { type: "text", text: `Error: ${(err as Error).message}` },
          ],
          isError: true,
        };
      }

      return {
        content: withDisclaimer([
          {
            type: "text",
            text: [
              `## Rerun Web Viewer embed`,
              ``,
              `**Container HTML:**`,
              "```html",
              result.html,
              "```",
              ``,
              `**Module script:**`,
              "```html",
              result.script,
              "```",
              ``,
              `**Full standalone document:**`,
              "```html",
              result.fullDocument.trimEnd(),
              "```",
            ].join("\n"),
          },
        ]),
        structuredContent: { ...result },
      };
    }

    // ── explain_concept ───────────────────────────────────────────────────
    case "explain_concept": {
      const args = rawArgs ?? {};
      const concept = args.concept as RerunConcept;
      if (!concept || !RERUN_CONCEPTS.includes(concept)) {
        return {
          content: [
            {
              type: "text",
              text: `Invalid concept "${concept}". Valid: ${RERUN_CONCEPTS.join(", ")}`,
            },
          ],
          isError: true,
        };
      }

      return {
        content: [{ type: "text", text: explainConcept(concept) }],
      };
    }

    default:
      return {
        content: [
          {
            type: "text",
            text: `Unknown tool: "${toolName}". Available: setup_rerun_project, generate_ar_logger, generate_python_sidecar, embed_web_viewer, explain_concept`,
          },
        ],
        isError: true,
      };
  }
}
