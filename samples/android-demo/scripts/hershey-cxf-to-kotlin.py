#!/usr/bin/env python3
"""Vendors the Hershey Script Simplex font into `HersheyScriptSimplex.kt` (Ask in AR demo).

Usage:
    python3 -I samples/android-demo/scripts/hershey-cxf-to-kotlin.py <ScriptS.cxf> > \
        samples/android-demo/src/main/java/io/github/sceneview/demo/demos/internal/HersheyScriptSimplex.kt

The input is the Hershey Script Simplex glyph set in the CXF text format (one `[XXXX] c` header
per glyph, then `L x1,y1,x2,y2` segments and `PL`/`PLC` polylines of `x,y,bulge` triples). The
copy used for the committed file ships with QCAD (`QCAD.app/Contents/Resources/fonts/ScriptS.cxf`),
which carries the Hershey data unchanged.

Every coordinate in that file is a multiple of 3/7 of a CXF unit: the original Hershey grid. The
generator writes integer grid units, two characters per point (`chr(52 + x)`, `chr(52 + y)`),
strokes separated by a space. The range used, -12..31, maps onto `(`..`S`, so no character needs
escaping in a Kotlin string. Run at authoring time only, never from the build.
"""
import sys

GRID = 7.0 / 3.0
BASE = 52
FIRST, LAST = 0x21, 0x7D


def parse(path):
    glyphs = {}
    cur = None
    for raw in open(path, encoding='utf-8'):
        line = raw.strip()
        if line.startswith('['):
            cur = int(line[1:line.index(']')], 16)
            glyphs[cur] = []
            continue
        if cur is None or not line or line.startswith('#'):
            continue
        kind, _, rest = line.partition(' ')
        v = [float(t) for t in rest.split(',')]
        if kind == 'L':
            pts = [(v[0], v[1]), (v[2], v[3])]
        elif kind in ('PL', 'PLC'):
            if any(v[i] != 0 for i in range(2, len(v), 3)):
                raise SystemExit('arc bulges are not supported')
            pts = [(v[i], v[i + 1]) for i in range(0, len(v), 3)]
            if kind == 'PLC':
                pts.append(pts[0])
        else:
            raise SystemExit('unsupported CXF entity: ' + kind)
        grid = [(round(x * GRID), round(y * GRID)) for x, y in pts]
        strokes = glyphs[cur]
        # Segments that continue the previous one are one pen stroke.
        if strokes and strokes[-1][-1] == grid[0]:
            strokes[-1].extend(grid[1:])
        else:
            strokes.append(grid)
    return glyphs


def encode(strokes):
    out = []
    for stroke in strokes:
        for x, y in stroke:
            if not (40 <= BASE + x <= 90 and 40 <= BASE + y <= 90):
                raise SystemExit('coordinate out of range')
        out.append(''.join(chr(BASE + x) + chr(BASE + y) for x, y in stroke))
    return ' '.join(out)


# The script capitals T, I and J are near twins of each other (a looped stem with a hook), so
# "The" read as "Jhe" on camera. These three are drawn here instead, upright on the Hershey grid,
# then slanted like the script: T a bar and a straight stem, I a stem between two bars, J a bar
# and a hooked stem. One list of strokes per character, in writing order.
HAND_GLYPHS = {
    'T': [[(0, 19), (3, 20), (7, 20), (11, 21), (15, 21)], [(8, 20), (7, 10), (6, 0)]],
    'I': [[(2, 21), (12, 21)], [(7, 21), (6, 0)], [(1, 0), (11, 0)]],
    'J': [[(8, 21), (18, 21)], [(13, 21), (13, 8), (12, 4), (10, 1), (7, 0), (4, 1), (2, 3), (2, 5)]],
}
SLANT = 0.28


def slanted(strokes):
    return [[(round(x + SLANT * y), y) for x, y in stroke] for stroke in strokes]


def main():
    glyphs = parse(sys.argv[1])
    for c, strokes in HAND_GLYPHS.items():
        glyphs[ord(c)] = slanted(strokes)
    rows = []
    for code in range(FIRST, LAST + 1):
        data = encode(glyphs.get(code, []))
        rows.append('        "%s", // %s' % (data, 'U+%04X %s' % (code, chr(code))))
    print(HEADER + '\n'.join(rows) + FOOTER)


